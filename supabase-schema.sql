-- A&M storefront schema for Supabase.
-- Customer sign-in is managed by Supabase Auth; never store passwords here.
-- The app server should use the Supabase service_role key for trusted writes.

create or replace function public.is_store_admin()
returns boolean
language sql
stable
security invoker
set search_path = ''
as $$
  select coalesce((auth.jwt() -> 'app_metadata' ->> 'role') = 'admin', false);
$$;

revoke all on function public.is_store_admin() from public;
grant execute on function public.is_store_admin() to authenticated;

create table if not exists public.customer_profiles (
  id uuid primary key references auth.users (id) on delete cascade,
  first_name text not null default '',
  last_name text not null default '',
  email text unique,
  phone text not null default '',
  address text not null default '',
  city text not null default '',
  region text not null default '',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.products (
  id bigint generated by default as identity primary key,
  name text not null,
  category text not null check (category in ('Wigs', 'Beauty', 'Fragrance', 'Shoes')),
  detail text not null default '',
  description text not null default '',
  price numeric(18, 2) not null check (price >= 0),
  tag text not null default '',
  image text not null default '',
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.orders (
  id text primary key,
  customer_id uuid not null references public.customer_profiles (id) on delete restrict,
  status text not null default 'Pending - awaiting admin confirmation of bank transfer',
  payment_method text not null default 'Bank transfer',
  payment_status text not null default 'Pending admin confirmation',
  subtotal numeric(18, 2) not null check (subtotal >= 0),
  delivery_fee numeric(18, 2) not null default 0 check (delivery_fee >= 0),
  delivery_estimate boolean not null default false,
  delivery_tier text not null default '',
  delivery_origin text not null default '',
  customer_name text not null,
  customer_email text not null,
  customer_phone text not null,
  delivery_street text not null,
  delivery_city text not null,
  delivery_state text not null,
  total numeric(18, 2) not null check (total >= 0),
  payment_confirmed_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.order_items (
  id bigint generated by default as identity primary key,
  order_id text not null references public.orders (id) on delete cascade,
  product_id bigint references public.products (id) on delete set null,
  product_name text not null,
  image text not null default '',
  quantity integer not null check (quantity between 1 and 50),
  unit_price numeric(18, 2) not null check (unit_price >= 0),
  line_total numeric(18, 2) generated always as (unit_price * quantity) stored
);

create table if not exists public.customer_notifications (
  id uuid primary key default gen_random_uuid(),
  customer_id uuid not null references public.customer_profiles (id) on delete cascade,
  subject text not null,
  message text not null,
  created_at timestamptz not null default now(),
  read_at timestamptz
);

create table if not exists public.contact_messages (
  id uuid primary key default gen_random_uuid(),
  name text not null check (length(btrim(name)) between 1 and 120),
  phone text not null check (length(btrim(phone)) between 1 and 40),
  message text not null check (length(btrim(message)) between 1 and 2000),
  is_read boolean not null default false,
  created_at timestamptz not null default now()
);

create table if not exists public.newsletter_subscribers (
  id bigint generated by default as identity primary key,
  email text not null unique check (
    email = lower(btrim(email))
    and email ~ '^[^[:space:]@]+@[^[:space:]@]+\.[^[:space:]@]+$'
  ),
  subscribed_at timestamptz not null default now()
);

create index if not exists orders_customer_created_idx
  on public.orders (customer_id, created_at desc);
create index if not exists order_items_order_idx
  on public.order_items (order_id);
create index if not exists customer_notifications_customer_created_idx
  on public.customer_notifications (customer_id, created_at desc);
create index if not exists contact_messages_created_idx
  on public.contact_messages (created_at desc);

create or replace function public.set_updated_at()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists customer_profiles_set_updated_at on public.customer_profiles;
create trigger customer_profiles_set_updated_at
before update on public.customer_profiles
for each row execute function public.set_updated_at();

drop trigger if exists products_set_updated_at on public.products;
create trigger products_set_updated_at
before update on public.products
for each row execute function public.set_updated_at();

drop trigger if exists orders_set_updated_at on public.orders;
create trigger orders_set_updated_at
before update on public.orders
for each row execute function public.set_updated_at();

create or replace function public.create_customer_profile()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  insert into public.customer_profiles (id, first_name, last_name, email)
  values (
    new.id,
    coalesce(nullif(btrim(new.raw_user_meta_data ->> 'first_name'), ''), ''),
    coalesce(nullif(btrim(new.raw_user_meta_data ->> 'last_name'), ''), ''),
    new.email
  )
  on conflict (id) do update
    set email = excluded.email;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created_profile on auth.users;
create trigger on_auth_user_created_profile
after insert on auth.users
for each row execute function public.create_customer_profile();

