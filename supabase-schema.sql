-- A&M storefront schema for Supabase.
-- Customer sign-in is managed by Supabase Auth; never store passwords here.
-- The app server should use the Supabase service_role key for trusted writes.

create or replace function public.is_store_admin()
returns boolean
language sql
stable
security invoker
set search_path = ''
as $$
  select coalesce((auth.jwt() -> 'app_metadata' ->> 'role') = 'admin', false);
$$;

revoke all on function public.is_store_admin() from public;
grant execute on function public.is_store_admin() to authenticated;

create table if not exists public.customer_profiles (
  id uuid primary key references auth.users (id) on delete cascade,
  first_name text not null default '',
  last_name text not null default '',
  email text unique,
  phone text not null default '',
  address text not null default '',
  city text not null default '',
  region text not null default '',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.products (
  id bigint generated by default as identity primary key,
  name text not null,
  category text not null check (category in ('Wigs', 'Beauty', 'Fragrance', 'Shoes')),
  detail text not null default '',
  description text not null default '',
  price numeric(18, 2) not null check (price >= 0),
  tag text not null default '',
  image text not null default '',
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.orders (
  id text primary key,
  customer_id uuid not null references public.customer_profiles (id) on delete restrict,
  status text not null default 'Pending - awaiting admin confirmation of bank transfer',
  payment_method text not null default 'Bank transfer',
  payment_status text not null default 'Pending admin confirmation',
  subtotal numeric(18, 2) not null check (subtotal >= 0),
  delivery_fee numeric(18, 2) not null default 0 check (delivery_fee >= 0),
  delivery_estimate boolean not null default false,
  delivery_tier text not null default '',
  delivery_origin text not null default '',
  customer_name text not null,
  customer_email text not null,
  customer_phone text not null,
  delivery_street text not null,
  delivery_city text not null,
  delivery_state text not null,
  total numeric(18, 2) not null check (total >= 0),
  payment_confirmed_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.order_items (
  id bigint generated by default as identity primary key,
  order_id text not null references public.orders (id) on delete cascade,
  product_id bigint references public.products (id) on delete set null,
  product_name text not null,
  image text not null default '',
  quantity integer not null check (quantity between 1 and 50),
  unit_price numeric(18, 2) not null check (unit_price >= 0),
  line_total numeric(18, 2) generated always as (unit_price * quantity) stored
);

create table if not exists public.customer_notifications (
  id uuid primary key default gen_random_uuid(),
  customer_id uuid not null references public.customer_profiles (id) on delete cascade,
  subject text not null,
  message text not null,
  created_at timestamptz not null default now(),
  read_at timestamptz
);

create table if not exists public.app_sessions (
  token_hash text primary key check (token_hash ~ '^[a-f0-9]{64}$'),
  role text not null,
  customer_id uuid references public.customer_profiles (id) on delete cascade,
  expires_at timestamptz not null,
  created_at timestamptz not null default now()
);

alter table public.app_sessions drop constraint if exists app_sessions_role_check;
alter table public.app_sessions drop constraint if exists app_sessions_check;
alter table public.app_sessions
  add constraint app_sessions_role_check check (role in ('customer', 'admin', 'hub')),
  add constraint app_sessions_check check (
    (role = 'customer' and customer_id is not null)
    or (role in ('admin', 'hub') and customer_id is null)
  );

create table if not exists public.hub_staff_accounts (
  id uuid primary key,
  email text not null unique check (
    email = lower(btrim(email))
    and email ~ '^[^[:space:]@]+@[^[:space:]@]+\.[^[:space:]@]+$'
  ),
  password_salt text not null check (password_salt ~ '^[a-f0-9]{32}$'),
  password_hash text not null check (password_hash ~ '^[a-f0-9]{128}$'),
  verification_token_hash text check (verification_token_hash is null or verification_token_hash ~ '^[a-f0-9]{64}$'),
  verification_expires_at timestamptz,
  verified_at timestamptz,
  created_at timestamptz not null default now()
);

create table if not exists public.contact_messages (
  id uuid primary key default gen_random_uuid(),
  name text not null check (length(btrim(name)) between 1 and 120),
  phone text not null check (length(btrim(phone)) between 1 and 40),
  message text not null check (length(btrim(message)) between 1 and 2000),
  is_read boolean not null default false,
  created_at timestamptz not null default now()
);

create table if not exists public.newsletter_subscribers (
  id bigint generated by default as identity primary key,
  email text not null unique check (
    email = lower(btrim(email))
    and email ~ '^[^[:space:]@]+@[^[:space:]@]+\.[^[:space:]@]+$'
  ),
  subscribed_at timestamptz not null default now()
);

create index if not exists orders_customer_created_idx
