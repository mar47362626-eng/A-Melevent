drop policy if exists "Customers and admins can read profiles" on public.customer_profiles;
create policy "Customers and admins can read profiles"
on public.customer_profiles for select to authenticated
using ((select auth.uid()) = id or (select public.is_store_admin()));

drop policy if exists "Customers can update their own profile" on public.customer_profiles;
create policy "Customers can update their own profile"
on public.customer_profiles for update to authenticated
using ((select auth.uid()) = id)
with check ((select auth.uid()) = id);

drop policy if exists "Anyone can read active products" on public.products;
create policy "Anyone can read active products"
on public.products for select to anon, authenticated
using (is_active or (select public.is_store_admin()));

drop policy if exists "Admins can manage products" on public.products;
create policy "Admins can manage products"
on public.products for all to authenticated
using ((select public.is_store_admin()))
with check ((select public.is_store_admin()));

drop policy if exists "Customers and admins can read orders" on public.orders;
create policy "Customers and admins can read orders"
on public.orders for select to authenticated
using (customer_id = (select auth.uid()) or (select public.is_store_admin()));

drop policy if exists "Admins can update orders" on public.orders;
create policy "Admins can update orders"
on public.orders for update to authenticated
using ((select public.is_store_admin()))
with check ((select public.is_store_admin()));

drop policy if exists "Customers and admins can read order items" on public.order_items;
create policy "Customers and admins can read order items"
on public.order_items for select to authenticated
using (
  exists (
    select 1
    from public.orders
    where orders.id = order_items.order_id
      and (orders.customer_id = (select auth.uid()) or (select public.is_store_admin()))
  )
);

drop policy if exists "Customers and admins can read notifications" on public.customer_notifications;
create policy "Customers and admins can read notifications"
on public.customer_notifications for select to authenticated
using (customer_id = (select auth.uid()) or (select public.is_store_admin()));

