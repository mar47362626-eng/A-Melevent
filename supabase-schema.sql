drop policy if exists "Customers and admins can read profiles" on public.customer_profiles;
create policy "Customers and admins can read profiles"
on public.customer_profiles for select to authenticated
using ((select auth.uid()) = id or (select public.is_store_admin()));

drop policy if exists "Customers can update their own profile" on public.customer_profiles;
create policy "Customers can update their own profile"
on public.customer_profiles for update to authenticated
using ((select auth.uid()) = id)
with check ((select auth.uid()) = id);

drop policy if exists "Anyone can read active products" on public.products;
create policy "Anyone can read active products"
on public.products for select to anon, authenticated
using (is_active or (select public.is_store_admin()));

drop policy if exists "Admins can manage products" on public.products;
create policy "Admins can manage products"
on public.products for all to authenticated
using ((select public.is_store_admin()))
with check ((select public.is_store_admin()));

drop policy if exists "Customers and admins can read orders" on public.orders;
create policy "Customers and admins can read orders"
on public.orders for select to authenticated
using (customer_id = (select auth.uid()) or (select public.is_store_admin()));

drop policy if exists "Admins can update orders" on public.orders;
create policy "Admins can update orders"
on public.orders for update to authenticated
using ((select public.is_store_admin()))
with check ((select public.is_store_admin()));

drop policy if exists "Customers and admins can read order items" on public.order_items;
create policy "Customers and admins can read order items"
on public.order_items for select to authenticated
using (
  exists (
    select 1
    from public.orders
    where orders.id = order_items.order_id
      and (orders.customer_id = (select auth.uid()) or (select public.is_store_admin()))
  )
);

drop policy if exists "Customers and admins can read notifications" on public.customer_notifications;
create policy "Customers and admins can read notifications"
on public.customer_notifications for select to authenticated
using (customer_id = (select auth.uid()) or (select public.is_store_admin()));

drop policy if exists "Customers can mark their notifications read" on public.customer_notifications;
create policy "Customers can mark their notifications read"
on public.customer_notifications for update to authenticated
using (customer_id = (select auth.uid()))
with check (customer_id = (select auth.uid()));

drop policy if exists "Visitors can send contact messages" on public.contact_messages;
create policy "Visitors can send contact messages"
on public.contact_messages for insert to anon, authenticated
with check (
  length(btrim(name)) between 1 and 120
  and length(btrim(phone)) between 1 and 40
  and length(btrim(message)) between 1 and 2000
);

drop policy if exists "Admins can read contact messages" on public.contact_messages;
create policy "Admins can read contact messages"
on public.contact_messages for select to authenticated
using ((select public.is_store_admin()));

drop policy if exists "Admins can update contact messages" on public.contact_messages;
create policy "Admins can update contact messages"
on public.contact_messages for update to authenticated
using ((select public.is_store_admin()))
with check ((select public.is_store_admin()));

drop policy if exists "Visitors can subscribe to newsletter" on public.newsletter_subscribers;
create policy "Visitors can subscribe to newsletter"
on public.newsletter_subscribers for insert to anon, authenticated
with check (
  email = lower(btrim(email))
  and email ~ '^[^[:space:]@]+@[^[:space:]@]+\.[^[:space:]@]+$'
);

drop policy if exists "Admins can read newsletter subscribers" on public.newsletter_subscribers;
create policy "Admins can read newsletter subscribers"
on public.newsletter_subscribers for select to authenticated
using ((select public.is_store_admin()));

grant select on public.products to anon, authenticated;
grant insert on public.contact_messages, public.newsletter_subscribers to anon, authenticated;
grant select on public.customer_profiles, public.orders, public.order_items, public.customer_notifications to authenticated;
grant update (first_name, last_name, phone, address, city, region)
  on public.customer_profiles to authenticated;
grant update (read_at) on public.customer_notifications to authenticated;
grant update (status, payment_status, payment_confirmed_at)
  on public.orders to authenticated;
grant update (is_read) on public.contact_messages to authenticated;
grant insert, select, update, delete on public.products to authenticated;
grant all privileges on public.customer_profiles, public.products, public.orders,
  public.order_items, public.customer_notifications, public.contact_messages,
  public.newsletter_subscribers to service_role;
grant usage, select on all sequences in schema public to service_role;
